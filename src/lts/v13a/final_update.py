def run():
    fp = ROOT / "report" / "REPORT_FINAL.md"
    sp = ROOT / "report" / "SUMMARY.md"
    F, S = fp.read_text(), sp.read_text()
    if MARK in F or MARK in S:
        F, S = _base("report/REPORT_FINAL.md"), _base("report/SUMMARY.md")
    summary_par, s10, s11, summ = texts()
    # REPORT_FINAL: §1 paragraph after the 9b paragraph
    i = F.index("**Итерация 9б (к выводу 8 и закону тенденции).**")
    j = F.index("\n", i)
    F = F[:j + 1] + "\n" + summary_par + "\n" + F[j + 1:]
    # §9 status and the BEA item
    F = F.replace("**Статус после итерации 12б** (пункты", "**Статус после итерации 13а** (пункты")
    F = F.replace("* **ошибка данных BEA (страхование):**", "* ~~**ошибка данных BEA (страхование)**~~ — **закрыт в "
                  "итерации 13а** (этап 4: с отношением самозанятых по секции K метки исходов 7 и 18 не меняются). Было:",
                  1)
    k = F.index("**Исходный список (итоговый отчёт):**")
    new_open = ("**Новые открытые вопросы после итерации 13а:**\n"
                "* **оценка поколений капитала до 1947 г.** в часах года покупки: от неё зависит знак нормы внутри фазы "
                "1948–1973 гг. (индекс `uslt4x` или λ_1947);\n"
                "* **граница производительного труда и место оплаты непроизводительного** (в S или в издержках) решают "
                "знак марксовой нормы США; нужен тест, различающий эти построения не по знаку тренда;\n"
                "* **проверка теоремы Окисио** по равновесной единой норме и жизнеспособности изменений техники (114ʹ) "
                "не сделана;\n"
                "* **мировые часы:** самозанятые и крестьяне в часах EXIOBASE, неоднородность часов разных стран "
                "(т. I, гл. 20), матрицы капитала другой версии EXIOBASE (3.8.2);\n"
                "* **вариант часов JHS** (1948–2010) не построен.\n\n")
    F = F[:k] + new_open + F[k:]
    # §10 block before "## 11."
    k = F.index("## 11. Особая роль труда")
    F = F[:k] + "\n".join(s10) + "\n" + F[k:]
    # §11.8 before the appendix separator
    k = F.index("---\n\n---\n\n## Приложения")
    F = F[:k] + "\n".join(s11) + "\n" + F[k:]
    fp.write_text(F)
    # SUMMARY
    S = S.replace("## Итерации 5–12б (после итогового отчёта)", "## Итерации 5–13а (после итогового отчёта)")
    S = S.replace("Четырнадцать итераций (1–12, включая 9б и 12б)", "Пятнадцать итераций (1–13а, включая 9б и 12б)")
    k = S.index("## Как менялись выводы")
    S = S[:k] + "\n".join(summ) + "\n" + S[k:]
    S = S.replace("**Открыто** (статус после итерации 12б", "**Открыто** (статус после итерации 13а")
    S = S.replace("* ошибка BEA (страхование) в итерациях 1–4, 7, 8, 10;", "* ошибка BEA (страхование) в итерациях 1–4, "
                  "7, 8, 10 — закрыто (итерация 13а, метки не меняются);")
    S = S.rstrip("\n") + ("\n* оценка поколений капитала до 1947 г.; граница производительного труда и место оплаты "
                          "непроизводительного; теорема Окисио по равновесной норме (114ʹ); часы мира с самозанятыми — "
                          "открыто (итерация 13а).\n")
    sp.write_text(S)
    print("REPORT_FINAL and SUMMARY updated")


if __name__ == "__main__":
    run()
