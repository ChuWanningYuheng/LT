def _base(path):
    return subprocess.run(["git", "-C", str(ROOT), "show", f"{BASE}:{path}"], check=True, capture_output=True,
                          text=True).stdout


def numbers():
    O = pd.read_csv(R / "s1_outcomes.csv")
    o = {int(n): g.iloc[0] for n, g in O.groupby("no")}
    ex = pd.read_csv(R / "s1_extra_after_results.csv").set_index("item")
    ident = pd.read_csv(R / "s1_identity.csv").set_index("series")
    s2 = pd.read_csv(R / "s2_outcomes.csv").iloc[0]
    fix = pd.read_csv(R / "s4_insurance_fix.csv").set_index("outcome")
    O3 = pd.read_csv(R / "s3_outcomes.csv") if (R / "s3_outcomes.csv").exists() else None
    w = {int(n): g.iloc[0] for n, g in O3.groupby("no")} if O3 is not None else {}
    rule = pd.read_csv(R / "s1_rule.csv").set_index("item").value
    return o, ex, ident, s2, fix, w, rule


